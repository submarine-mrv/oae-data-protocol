"""Manage the schema's NERC Vocabulary Server (NVS) terms.

fetch  Download the collections in nvs-vocabs.yaml and snapshot the concepts the schema uses
       into ontologies/nvs/<code>.json. Needs network access.
sync   Regenerate nvs_enums.yaml from nvs-vocabs.yaml and the snapshots. Keeps existing keys.
check  Verify every NVS reference in the schema against the snapshots. Offline; run by `just test`.
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "nvs-vocabs.yaml"
SNAPSHOTS = ROOT / "ontologies" / "nvs"
SCHEMA_DIR = ROOT / "src" / "oae_data_protocol" / "schema"
MAIN_SCHEMA = SCHEMA_DIR / "oae_data_protocol.yaml"
GENERATED = SCHEMA_DIR / "nvs_enums.yaml"
BASE = "http://vocab.nerc.ac.uk/collection/{}/current/"
SOURCE = "https://vocab.nerc.ac.uk/collection/{}/current/?_profile=nvs&_mediatype=application/ld+json"
CURIE = re.compile(r"\b(NVS|SDN)_([A-Z0-9]+):([A-Za-z0-9.]+)(/?)")

HEADER = """\
# Generated by scripts/nvs.py from nvs-vocabs.yaml and ontologies/nvs/. Refresh with `just vocab-sync`.
# A sync keeps existing keys, so a key can be renamed here by hand. Titles and descriptions come
# from NVS and are overwritten.
"""


def load_config():
    return yaml.safe_load(CONFIG.read_text())


def schema_files():
    return sorted(
        p for p in SCHEMA_DIR.glob("*.yaml") if p.name != "dynamic_enums_expanded.yaml"
    )


def referenced_codes():
    """NVS codes the schema references, by collection."""
    refs = {}
    for path in schema_files():
        for m in CURIE.finditer(path.read_text()):
            refs.setdefault(m.group(2), set()).add(m.group(3))
    return refs


def text(value):
    if isinstance(value, dict):
        return value.get("@value", "")
    if isinstance(value, list):
        return " ".join(text(v) for v in value)
    return value or ""


def load_snapshot(collection):
    path = SNAPSHOTS / f"{collection}.json"
    return {c["code"]: c for c in json.loads(path.read_text())} if path.exists() else {}


def fetch():
    config = load_config()
    refs = referenced_codes()
    SNAPSHOTS.mkdir(parents=True, exist_ok=True)
    for collection in config["collections"]:
        with urllib.request.urlopen(SOURCE.format(collection), timeout=300) as response:
            graph = json.load(response)["@graph"]
        concepts = {}
        for node in graph:
            if "skos:prefLabel" not in node:
                continue
            uri = node["@id"]
            code = uri.removeprefix(BASE.format(collection)).rstrip("/")
            if not code or "/" in code:
                continue
            concepts[code] = {
                "code": code,
                "uri": uri,
                "label": text(node.get("skos:prefLabel")).strip(),
                "definition": text(node.get("skos:definition")).strip(),
                "deprecated": node.get("owl:deprecated") == "true",
            }
        keep = set(refs.get(collection, set()))
        for enum in config["enums"].values():
            if enum["collection"] == collection:
                keep |= (
                    set(concepts) if enum["include"] == "all" else set(enum["include"])
                )
        missing = sorted(keep - set(concepts))
        if missing:
            print(f"{collection}: not in NVS: {', '.join(missing)}", file=sys.stderr)
        rows = [concepts[c] for c in sorted(keep & set(concepts))]
        (SNAPSHOTS / f"{collection}.json").write_text(
            json.dumps(rows, indent=1, ensure_ascii=False) + "\n"
        )
        print(f"{collection}: {len(rows)} of {len(concepts)} concepts")


def slug(label):
    return re.sub(r"[^a-z0-9]+", "_", label.lower()).strip("_")


def existing_keys():
    """meaning -> key in the current generated file."""
    if not GENERATED.exists():
        return {}
    enums = yaml.safe_load(GENERATED.read_text()).get("enums") or {}
    return {
        pv.get("meaning"): key
        for enum in enums.values()
        for key, pv in (enum.get("permissible_values") or {}).items()
    }


def generate():
    config = load_config()
    keys = existing_keys()
    enums = {}
    for name, spec in config["enums"].items():
        collection = spec["collection"]
        snapshot = load_snapshot(collection)
        codes = snapshot if spec["include"] == "all" else spec["include"]
        concepts = [
            snapshot[c]
            for c in codes
            if c in snapshot and not snapshot[c]["deprecated"]
        ]
        values, used = {}, set()
        for concept in sorted(concepts, key=lambda c: c["label"].lower()):
            meaning = f"NVS_{collection}:{concept['code']}/"
            key = keys.get(meaning) or slug(concept["label"])
            if key in used:
                key = f"{key}_{slug(concept['code'])}"
            used.add(key)
            value = {"title": concept["label"]}
            if concept["definition"]:
                value["description"] = concept["definition"]
            value["meaning"] = meaning
            values[key] = value
        enums[name] = {"description": spec["description"], "permissible_values": values}
    body = {
        "id": "https://schema.oaedata.org/nvs_enums",
        "name": "NvsEnums",
        "prefixes": {"oae": "https://schema.oaedata.org/"}
        | {
            f"NVS_{c}": BASE.format(c)
            for c in sorted({e["collection"] for e in config["enums"].values()})
        },
        "default_prefix": "oae",
        "enums": enums,
    }
    return (
        HEADER
        + "\n"
        + yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=100)
    )


def sync():
    GENERATED.write_text(generate())
    print(f"wrote {GENERATED.relative_to(ROOT)}")


def problems():
    config = load_config()
    collections = set(config["collections"])
    snapshots = {c: load_snapshot(c) for c in collections}
    found = []

    prefixes = yaml.safe_load(MAIN_SCHEMA.read_text()).get("prefixes") or {}
    for collection in sorted(collections):
        expected = BASE.format(collection)
        if prefixes.get(f"NVS_{collection}") != expected:
            found.append(
                f"{MAIN_SCHEMA.name}: prefix NVS_{collection} must expand to {expected}"
            )
        if not snapshots[collection]:
            found.append(
                f"ontologies/nvs/{collection}.json is missing; run `just vocab-fetch`"
            )

    for path in schema_files():
        for lineno, line in enumerate(path.read_text().splitlines(), 1):
            for m in CURIE.finditer(line):
                where = f"{path.name}:{lineno}: {m.group(0)}"
                kind, collection, code, slash = m.groups()
                if kind == "SDN":
                    found.append(f"{where}: use the NVS_{collection} prefix")
                elif collection not in collections:
                    found.append(
                        f"{where}: collection {collection} is not in nvs-vocabs.yaml"
                    )
                elif not slash:
                    found.append(
                        f"{where}: needs a trailing slash to expand to the canonical NVS URI"
                    )
                elif code not in snapshots[collection]:
                    found.append(
                        f"{where}: not in the snapshot (unknown term, or run `just vocab-fetch`)"
                    )
                elif snapshots[collection][code]["deprecated"]:
                    found.append(f"{where}: deprecated in NVS")

    if not GENERATED.exists() or GENERATED.read_text() != generate():
        found.append(f"{GENERATED.name} is out of date; run `just vocab-sync`")
    return found


def check():
    found = problems()
    for problem in found:
        print(problem, file=sys.stderr)
    print(f"{len(found)} NVS problem(s)" if found else "NVS references OK")
    return 1 if found else 0


if __name__ == "__main__":
    commands = {"fetch": fetch, "sync": sync, "check": check}
    if len(sys.argv) != 2 or sys.argv[1] not in commands:
        sys.exit(__doc__)
    sys.exit(commands[sys.argv[1]]() or 0)
